// Command genscripts writes scripts_gen.go, the "all scripts" font pack:
// the Regular weight of every Noto Sans family on notofonts.github.io (one
// per script), with the family name read from each font, in fallback order.
//
//	go generate ./internal/config
package main

import (
	"encoding/binary"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"os"
	"slices"
	"strings"
	"sync"
	"unicode/utf16"
)

const repo = "https://raw.githubusercontent.com/notofonts/notofonts.github.io/main/fonts/"

// first are the living scripts most programs show, in fallback order; the
// rest follow alphabetically.
var first = []string{
	"NotoSans", "NotoSansArabic", "NotoSansHebrew", "NotoSansThai", "NotoSansDevanagari", "NotoSansBengali",
	"NotoSansTamil", "NotoSansTamilSupplement", "NotoSansTelugu", "NotoSansKannada", "NotoSansMalayalam",
	"NotoSansGujarati", "NotoSansGurmukhi", "NotoSansOriya", "NotoSansSinhala", "NotoSansKhmer", "NotoSansLao",
	"NotoSansMyanmar", "NotoSansGeorgian", "NotoSansArmenian", "NotoSansEthiopic", "NotoSansThaana",
	"NotoSansMongolian", "NotoSansSyriac", "NotoSansSymbols", "NotoSansSymbols2", "NotoSansMath",
}

// alternates of a script already in the pack, and a test font.
func alternate(f string) bool {
	return strings.HasSuffix(f, "UI") || strings.Contains(f, "Unjoined") || strings.Contains(f, "Looped") ||
		strings.Contains(f, "Mono") || strings.Contains(f, "Display") || strings.HasSuffix(f, "Test")
}

type face struct {
	dir, family string
	size        int
}

func main() {
	req, _ := http.NewRequest("GET", "https://api.github.com/repos/notofonts/notofonts.github.io/contents/fonts", nil)
	if t := os.Getenv("GITHUB_TOKEN"); t != "" {
		req.Header.Set("Authorization", "Bearer "+t)
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		fail(err)
	}
	var ents []struct{ Name string }
	if err := json.NewDecoder(resp.Body).Decode(&ents); err != nil {
		fail(err)
	}
	resp.Body.Close()
	var dirs []string
	for _, e := range ents {
		if strings.HasPrefix(e.Name, "NotoSans") && !alternate(e.Name) {
			dirs = append(dirs, e.Name)
		}
	}
	slices.SortFunc(dirs, func(a, b string) int {
		ia, ib := slices.Index(first, a), slices.Index(first, b)
		switch {
		case ia >= 0 && ib >= 0:
			return ia - ib
		case ia >= 0:
			return -1
		case ib >= 0:
			return 1
		}
		return strings.Compare(a, b)
	})

	faces := make([]face, len(dirs))
	var wg sync.WaitGroup
	sem := make(chan struct{}, 8)
	for i, d := range dirs {
		wg.Add(1)
		go func() {
			defer wg.Done()
			sem <- struct{}{}
			defer func() { <-sem }()
			r, err := http.Get(repo + d + "/hinted/ttf/" + d + "-Regular.ttf")
			if err != nil || r.StatusCode != 200 {
				fmt.Fprintln(os.Stderr, "skip", d, err)
				return
			}
			b, _ := io.ReadAll(r.Body)
			r.Body.Close()
			faces[i] = face{dir: d, family: family(b), size: len(b)}
		}()
	}
	wg.Wait()

	var b strings.Builder
	b.WriteString("// Code generated by genscripts from notofonts.github.io; DO NOT EDIT.\n\npackage config\n\n")
	b.WriteString("// scriptFaces are the \"all scripts\" pack, in fallback order.\nvar scriptFaces = []scriptFace{\n")
	for _, f := range faces {
		if f.family == "" {
			continue
		}
		fmt.Fprintf(&b, "\t{%q, %q, %d},\n", f.dir, f.family, f.size)
	}
	b.WriteString("}\n")
	if err := os.WriteFile("scripts_gen.go", []byte(b.String()), 0o644); err != nil {
		fail(err)
	}
}

// family reads the typographic (16) or family (1) name from a TrueType
// name table, preferring the Windows Unicode records.
func family(b []byte) string {
	if len(b) < 12 {
		return ""
	}
	n := int(binary.BigEndian.Uint16(b[4:]))
	for i := 0; i < n; i++ {
		rec := b[12+16*i:]
		if string(rec[:4]) != "name" {
			continue
		}
		off := int(binary.BigEndian.Uint32(rec[8:]))
		t := b[off:]
		count, strs := int(binary.BigEndian.Uint16(t[2:])), off+int(binary.BigEndian.Uint16(t[4:]))
		names := map[uint16]string{}
		for j := 0; j < count; j++ {
			r := t[6+12*j:]
			platform, enc, id := binary.BigEndian.Uint16(r), binary.BigEndian.Uint16(r[2:]), binary.BigEndian.Uint16(r[6:])
			if platform != 3 || enc != 1 || (id != 1 && id != 16) {
				continue
			}
			l, o := int(binary.BigEndian.Uint16(r[8:])), int(binary.BigEndian.Uint16(r[10:]))
			raw := b[strs+o : strs+o+l]
			u := make([]uint16, l/2)
			for k := range u {
				u[k] = binary.BigEndian.Uint16(raw[2*k:])
			}
			names[id] = string(utf16.Decode(u))
		}
		if names[16] != "" {
			return names[16]
		}
		return names[1]
	}
	return ""
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
