// Command genlocales writes locales_gen.go, the region list the GUI offers:
// every UTF-8 locale glibc supports (/usr/share/i18n/SUPPORTED), named in
// its own language from the locale sources' lang_name and country_name.
// Run on a host with glibc's locale sources (Debian: the locales package):
//
//	go generate ./internal/config
package main

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"
)

const i18n = "/usr/share/i18n"

var (
	idRe   = regexp.MustCompile(`^([a-z]{2,3}_[A-Z]{2})(\.UTF-8)? UTF-8$`)
	uniRe  = regexp.MustCompile(`<U([0-9A-Fa-f]{4,6})>`)
	field  = regexp.MustCompile(`^(lang_name|country_name)\s+"(.*)"`)
	copyRe = regexp.MustCompile(`^copy\s+"([^"]+)"`)
)

// names reads lang_name and country_name from a locale's LC_ADDRESS,
// following its copy line when it borrows the section.
func names(id string, depth int) (lang, country string) {
	f, err := os.Open(filepath.Join(i18n, "locales", id))
	if err != nil || depth > 4 {
		return "", ""
	}
	defer f.Close()
	in := false
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		l := strings.TrimSpace(sc.Text())
		switch {
		case l == "LC_ADDRESS":
			in = true
		case l == "END LC_ADDRESS":
			return lang, country
		case !in:
		case copyRe.MatchString(l):
			return names(copyRe.FindStringSubmatch(l)[1], depth+1)
		case field.MatchString(l):
			m := field.FindStringSubmatch(l)
			v := uniRe.ReplaceAllStringFunc(m[2], func(u string) string {
				n, _ := strconv.ParseInt(uniRe.FindStringSubmatch(u)[1], 16, 32)
				return string(rune(n))
			})
			if m[1] == "lang_name" {
				lang = v
			} else {
				country = v
			}
		}
	}
	return lang, country
}

func title(s string) string {
	r, n := utf8.DecodeRuneInString(s)
	return string(unicode.ToUpper(r)) + s[n:]
}

func main() {
	f, err := os.Open(filepath.Join(i18n, "SUPPORTED"))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	seen := map[string]bool{}
	var ids []string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		if m := idRe.FindStringSubmatch(sc.Text()); m != nil && !seen[m[1]] {
			seen[m[1]] = true
			ids = append(ids, m[1])
		}
	}
	f.Close()
	sort.Strings(ids)

	var b strings.Builder
	b.WriteString("// Code generated by genlocales from glibc's locale sources; DO NOT EDIT.\n\npackage config\n\n")
	b.WriteString("// allLocales are glibc's UTF-8 locales, named in their own language.\nvar allLocales = []Locale{\n")
	for _, id := range ids {
		lang, country := names(id, 0)
		name := id
		if lang != "" {
			name = title(lang)
			if country != "" {
				name += "（" + country + "）"
			}
		}
		fmt.Fprintf(&b, "\t{ID: %q, Name: %q},\n", id, name)
	}
	b.WriteString("}\n")
	if err := os.WriteFile("locales_gen.go", []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
